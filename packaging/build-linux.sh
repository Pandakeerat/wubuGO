#!/usr/bin/env bash
# Build on Fedora x86_64; requires python3-devel, python3-tkinter, python3-pip,
# binutils and (for RPM) rpm-build. Build host package installation is separate.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 -m venv .build-venv
.build-venv/bin/python -m pip install -r packaging/requirements-build.txt
.build-venv/bin/python -c 'import tkinter; print(tkinter.TkVersion)'
.build-venv/bin/python -m unittest discover -s tests -v
.build-venv/bin/python -m PyInstaller --clean --noconfirm packaging/wubuGO.spec
.build-venv/bin/python packaging/collect_licenses.py dist/wubuGO
if ! command -v xvfb-run >/dev/null 2>&1; then
    printf '%s\n' 'xvfb-run is required to validate the bundled GUI before packaging.' >&2
    exit 1
fi
xvfb-run -a dist/wubuGO/wubuGO --self-test "$PWD/dist/frozen-selftest.json"
.build-venv/bin/python -c 'import json; from pathlib import Path; assert json.loads(Path("dist/frozen-selftest.json").read_text())["ok"] is True'
cp packaging/install-linux.sh dist/wubuGO/install.sh
cp packaging/uninstall-linux.sh dist/wubuGO/uninstall.sh
cp packaging/README.md dist/wubuGO/BUILD-NOTES.md
cp assets/logo.png dist/wubuGO/wubugo.png
cp packaging/wubugo.desktop dist/wubuGO/wubugo.desktop
chmod +x dist/wubuGO/install.sh dist/wubuGO/uninstall.sh
# Keep the symlinks generated by PyInstaller; ZIP is unsuitable for this bundle.
tar -C dist -czf dist/wubuGO-6.0.0-linux-x64-portable.tar.gz wubuGO
if command -v rpmbuild >/dev/null 2>&1; then
    task_rpm_root="$PWD/build/rpm"
    mkdir -p "$task_rpm_root"/{BUILD,BUILDROOT,RPMS,SOURCES,SPECS,SRPMS}
    cp dist/wubuGO-6.0.0-linux-x64-portable.tar.gz "$task_rpm_root/SOURCES/"
    rpmbuild --define "_topdir $task_rpm_root" -bb packaging/wubugo-rpm.spec
    find "$task_rpm_root/RPMS" -name '*.rpm' -exec cp '{}' dist/ \;
fi
.build-venv/bin/python packaging/checksums.py dist
